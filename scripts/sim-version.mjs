// Writes src/sim/version.js: a fingerprint of every file that decides how the game plays.
// The Weekly Echo server only accepts runs made with the same simulation it replays them
// with, so any change to these files gives a new version. Run by `npm run build`; the
// tests fail if it is stale.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export function simFiles() {
  const sim = readdirSync(join(root, 'src/sim')).filter((f) => f.endsWith('.js') && f !== 'version.js').sort().map((f) => `src/sim/${f}`);
  return ['src/config.js', ...sim];
}
export function simVersion() {
  const h = createHash('sha256');
  for (const f of simFiles()) h.update(f + '\n' + readFileSync(join(root, f), 'utf8').replace(/\r\n/g, '\n'));
  return h.digest('hex').slice(0, 12);
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const v = simVersion();
  writeFileSync(join(root, 'src/sim/version.js'), `// Generated by scripts/sim-version.mjs: a fingerprint of the simulation code. Do not edit.\nexport const SIM_VERSION = '${v}';\n`);
  console.log('SIM_VERSION', v);
}
